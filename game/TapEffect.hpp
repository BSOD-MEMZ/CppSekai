// CppSekai - PJSK style global tap feedback.
//
// Reverse engineered from pjsk 7.1.0 `ScreenLayerTouchEffect` (see
// .workbuddy/memory + RE-report-jp.md): the real effect is a Unity
// ParticleSystem billboard playing a 4x4 texture sheet, NOT a scaled sprite.
// Measured values that drive the numbers below:
//   main ripple  PT_01 : 4x4 sheet, 16 tiles (14 used), startLifetime 0.5s,
//                        startSpeed 0 -> no travel, growth is baked into the art,
//                        frameOverTime linear 0->1 (~32 fps).
//   thin ring    PT_02 : same shape, life 0.45s, larger start size.
//   glow         single 256x256 radial flare, 0.5s fade.
// The flying shards are mesh particles in the original; here they are the
// existing gradient masks (tap_tri_1/2), which read the same at this size.
//
// Textures are generated by .workbuddy/tools/gen_tap_sheet.py (own art, so the
// repo stays clean); a missing sheet falls back to the old scaled tap_ring.png.
//
// Never spawned during the play state: there a pointer press is a note hit and
// the judgement input path must stay untouched (see main.cpp).
#pragma once

#include "imgui.h"

#include <string>
#include <vector>

namespace platform
{
class Renderer;
}

namespace game
{
class TapEffect
{
  public:
    // One flying shard.
    struct Piece
    {
        float angleDeg;    // flight direction
        float spinDeg;     // total rotation over its life
        bool outline;      // true = gradient outline mask, false = gradient fill
        float distanceScale;
        float sizeScale;
        ImU32 tint;        // per-piece color: the original fans out many hues
    };

    // Loads assets/fx/tap_*.png through the renderer's UI texture loader.
    // Missing files degrade to "not loaded" (the effect silently does nothing).
    bool load(platform::Renderer& renderer, const std::string& fxDir, std::string& outError);
    bool loaded() const { return mSheetA != 0 || mRing != 0; }

    // Spawns one burst at a window-pixel position with age 0.
    void spawn(float x, float y);
    // Same, but starts at a given age - used by --tap-fx-test so a headless
    // screenshot can show several phases at once.
    void spawnAt(float x, float y, float age);

    // Freezes ageing (headless verification only).
    void setFrozen(bool frozen) { mFrozen = frozen; }

    void update(float dt);
    // Draws on the foreground draw list (above every screen).
    void draw();

    void clear() { mActive.clear(); }

  private:
    struct Instance
    {
        float x = 0.0f;
        float y = 0.0f;
        float age = 0.0f;
        int seed = 0; // rotates the whole fan, keeps bursts varied
    };

    // One flipbook layer of a burst.
    struct FlipLayer
    {
        ImTextureID tex; // 0 = skip
        int tiles;       // tiles per row/column (4 => 4x4)
        int frames;      // frames actually used in the sheet
        float life;      // seconds
        float delay;     // start offset, seconds
        float diameter;  // design px at scale 1
        float alpha;     // overall multiplier
        bool single;     // true = single image, no UV tiling (the flare)
    };

    void layerList(FlipLayer (&out)[3]) const;
    void drawFlip(ImDrawList* dl, const Instance& in, const FlipLayer& layer, float scale) const;
    void drawRingLegacy(ImDrawList* dl, const Instance& in, float scale, float alphaScale,
        bool shadow) const;
    void drawShard(ImDrawList* dl, const Instance& in, const Piece& piece, float scale,
        float alphaScale, bool shadow) const;

    ImTextureID mSheetA = 0;    // 4x4 main ripple (14 of 16 tiles)
    ImTextureID mSheetB = 0;    // 4x4 thin ring (16 tiles)
    ImTextureID mFlare = 0;     // single radial glow
    ImTextureID mRing = 0;      // legacy fallback
    ImTextureID mFill = 0;      // gradient-filled irregular triangle
    ImTextureID mOutline = 0;   // gradient-outlined irregular triangle
    std::vector<Instance> mActive;
    int mNextSeed = 0;
    bool mFrozen = false;
};

} // namespace game
